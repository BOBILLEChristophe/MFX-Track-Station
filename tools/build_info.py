# PlatformIO pre-build script: writes src/BuildInfo.cpp with the date and
# time of this build. __DATE__ and __TIME__ in main.cpp only changed when
# main.cpp itself was compiled again, so a firmware built after a change in
# another file still showed an old date (3 Nov 2026). The file is generated
# at every build (its content changes, so it is always compiled again) and
# is not kept in Git.
Import("env")
import os
import time

path = os.path.join(env.subst("$PROJECT_SRC_DIR"), "BuildInfo.cpp")
stamp = time.strftime("%Y-%m-%d %H:%M:%S")
with open(path, "w") as f:
    f.write("// Generated by tools/build_info.py at each build: do not edit\n")
    f.write('#include "BuildInfo.h"\n')
    f.write('const char BUILD_DATE[] = "%s";\n' % stamp)
